#!/bin/bash
# Build the gpu_unlock kernel module and firmware packages for one Unraid kernel.
#
# usage: build/build.sh --src GPU_UNLOCK_SRC --kdir UNRAID_KDIR [--kernel 6.18.54-Unraid]
#                       [--system-map System.map] [--build 1] [--out build/out]
#
# UNRAID_KDIR must be the prepared tree of the target kernel (its .config,
# generated headers and, with CONFIG_MODVERSIONS, Module.symvers); a distribution
# kernel with the same version number is not a substitute. With --system-map,
# every symbol the module imports must be exported by that kernel. Linux x86_64 only.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
SRC="" KDIR="" KERNEL=6.18.54-Unraid SYSTEM_MAP="" BUILD=1 OUT=$HERE/out
while [ $# -gt 0 ]; do
  case $1 in
    --src) SRC=$(cd "$2" && pwd); shift 2 ;;
    --kdir) KDIR=$(cd "$2" && pwd); shift 2 ;;
    --kernel) KERNEL=$2; shift 2 ;;
    --system-map) SYSTEM_MAP=$2; shift 2 ;;
    --build) BUILD=$2; shift 2 ;;
    --out) OUT=$2; shift 2 ;;
    *) sed -n '2,10p' "$0" >&2; exit 2 ;;
  esac
done
[ -n "$SRC" ] && [ -n "$KDIR" ] || { sed -n '2,10p' "$0" >&2; exit 2; }
[ "$(uname -s)/$(uname -m)" = Linux/x86_64 ] || { echo "build on Linux x86_64" >&2; exit 1; }

VERSION=$(cat "$SRC/VERSION")
NV=$(sed -n 's/^NV *:= *//p' "$SRC/Makefile")
COMMIT=$(git -C "$SRC" rev-parse HEAD 2>/dev/null || echo unknown)
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$OUT"

make -C "$SRC/kernel/gpu_unlock" KDIR="$KDIR"
make -C "$SRC" ASSETS="$WORK/assets" assets
# Upstream tests, with the generated firmware, catch regressions from any local patch.
make -C "$SRC" ASSETS="$WORK/assets" test

KO=$SRC/kernel/gpu_unlock/gpu_unlock.ko
VERMAGIC=$(modinfo -F vermagic "$KO" | awk '{print $1}')
[ "$VERMAGIC" = "$KERNEL" ] || { echo "vermagic $VERMAGIC does not match $KERNEL" >&2; exit 1; }
if [ -n "$SYSTEM_MAP" ]; then
  missing=$(nm -u "$KO" | awk '{print $2}' | while read -r sym; do
    grep -q " __ksymtab_$sym\$" "$SYSTEM_MAP" || echo "$sym"
  done)
  [ -z "$missing" ] || { echo "not exported by $KERNEL: $missing" >&2; exit 1; }
  echo "imports: $(nm -u "$KO" | wc -l) symbols, all exported by $KERNEL"
fi

# Module package.
K=$WORK/kmod
install -Dm644 "$KO" "$K/lib/modules/$KERNEL/extra/gpu_unlock.ko"
install -Dm644 "$SRC/licenses/GPL-2.0.txt" "$K/usr/share/licenses/gpu-unlock-kmod/GPL-2.0.txt"
mkdir -p "$K/install"
cat > "$K/install/slack-desc" <<EOF
gpu-unlock-kmod: gpu-unlock-kmod (gpu_unlock $VERSION for $KERNEL)
gpu-unlock-kmod:
gpu-unlock-kmod: Ampere pre-driver BF16 unlock kernel module.
gpu-unlock-kmod: Upstream: https://github.com/Zagitta/gpu-unlock
gpu-unlock-kmod: Commit: $COMMIT
gpu-unlock-kmod: vermagic: $(modinfo -F vermagic "$KO")
gpu-unlock-kmod:
gpu-unlock-kmod:
gpu-unlock-kmod:
gpu-unlock-kmod:
gpu-unlock-kmod:
EOF

# Firmware package, at the paths the module declares.
F=$WORK/firmware
for fw in $(modinfo -F firmware "$KO"); do
  case $fw in gpu-unlock/"$NV"/*) ;; *) echo "unexpected firmware path $fw" >&2; exit 1 ;; esac
  install -Dm644 "$WORK/assets/$(basename "$fw")" "$F/lib/firmware/$fw"
done
for f in "$WORK/assets/NVIDIA-LICENSE" "$SRC/firmware/NOTICE.md" "$SRC/licenses/CMP40HX-MIT.txt" "$SRC/licenses/NVIDIA-MIT.txt"; do
  install -Dm644 "$f" "$F/usr/share/licenses/gpu-unlock-firmware/$(basename "$f")"
done
mkdir -p "$F/install"
cat > "$F/install/slack-desc" <<EOF
gpu-unlock-firmware: gpu-unlock-firmware (assets $NV for gpu_unlock $VERSION)
gpu-unlock-firmware:
gpu-unlock-firmware: Firmware generated by the gpu-unlock build from pinned NVIDIA inputs.
gpu-unlock-firmware: NVIDIA firmware remains under its own terms; see NOTICE.md.
gpu-unlock-firmware: Commit: $COMMIT
gpu-unlock-firmware:
gpu-unlock-firmware:
gpu-unlock-firmware:
gpu-unlock-firmware:
gpu-unlock-firmware:
gpu-unlock-firmware:
EOF

KMOD_TXZ=$OUT/gpu-unlock-kmod-$(echo "$VERSION" | tr - _)_$(echo "$KERNEL" | tr - _)-x86_64-$BUILD.txz
FW_TXZ=$OUT/gpu-unlock-firmware-$(echo "$NV" | tr - _)-noarch-$BUILD.txz
python3 "$HERE/mktxz.py" "$K" "$KMOD_TXZ"
python3 "$HERE/mktxz.py" "$F" "$FW_TXZ"

for txz in "$KMOD_TXZ" "$FW_TXZ"; do
  echo "== $(basename "$txz")"
  tar -tvJf "$txz"
done
echo "vermagic: $(modinfo -F vermagic "$KO")"
echo "firmware: $(modinfo -F firmware "$KO" | tr '\n' ' ')"
echo "upstream: $VERSION $COMMIT"
