#!/bin/bash
# Build the kernel module and firmware packages of one unlock project
# (Zagitta/gpu-unlock or nlzy/turing-unlock) for one Unraid kernel.
#
# usage: build/build.sh --src UPSTREAM_SRC --kdir UNRAID_KDIR [--kernel 6.18.54-Unraid]
#                       [--system-map System.map] [--build 1] [--out build/out]
#
# UNRAID_KDIR must be the prepared tree of the target kernel (its .config,
# generated headers and, with CONFIG_MODVERSIONS, Module.symvers); a distribution
# kernel with the same version number is not a substitute. With --system-map,
# every symbol the module imports must be exported by that kernel. Linux x86_64 only.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
SRC="" KDIR="" KERNEL=6.18.54-Unraid SYSTEM_MAP="" BUILD=1 OUT=$HERE/out
while [ $# -gt 0 ]; do
  case $1 in
    --src) SRC=$(cd "$2" && pwd); shift 2 ;;
    --kdir) KDIR=$(cd "$2" && pwd); shift 2 ;;
    --kernel) KERNEL=$2; shift 2 ;;
    --system-map) SYSTEM_MAP=$2; shift 2 ;;
    --build) BUILD=$2; shift 2 ;;
    --out) OUT=$2; shift 2 ;;
    *) sed -n '2,11p' "$0" >&2; exit 2 ;;
  esac
done
[ -n "$SRC" ] && [ -n "$KDIR" ] || { sed -n '2,11p' "$0" >&2; exit 2; }
[ "$(uname -s)/$(uname -m)" = Linux/x86_64 ] || { echo "build on Linux x86_64" >&2; exit 1; }

# Both upstreams keep their one module in kernel/<module>/; packages use the project name.
MODULE=$(basename "$(ls -d "$SRC"/kernel/*/ | head -n 1)")
PROJECT=$(echo "$MODULE" | tr _ -)
VERSION=$(cat "$SRC/VERSION")
NV=$(sed -n 's/^NV *:= *//p' "$SRC/Makefile")
COMMIT=$(git -C "$SRC" rev-parse HEAD 2>/dev/null || echo unknown)
ORIGIN=$(git -C "$SRC" remote get-url origin 2>/dev/null || echo unknown)
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$OUT"

make -C "$SRC/kernel/$MODULE" KDIR="$KDIR"
make -C "$SRC" ASSETS="$WORK/assets" assets
# Upstream tests, where there are any, catch regressions from any local patch.
if make -C "$SRC" -n test > /dev/null 2>&1; then
  make -C "$SRC" ASSETS="$WORK/assets" test
else
  echo "$PROJECT has no test target"
fi

KO=$SRC/kernel/$MODULE/$MODULE.ko
VERMAGIC=$(modinfo -F vermagic "$KO" | awk '{print $1}')
[ "$VERMAGIC" = "$KERNEL" ] || { echo "vermagic $VERMAGIC does not match $KERNEL" >&2; exit 1; }
if [ -n "$SYSTEM_MAP" ]; then
  missing=$(nm -u "$KO" | awk '{print $2}' | while read -r sym; do
    grep -q " __ksymtab_$sym\$" "$SYSTEM_MAP" || echo "$sym"
  done)
  [ -z "$missing" ] || { echo "not exported by $KERNEL: $missing" >&2; exit 1; }
  echo "imports: $(nm -u "$KO" | wc -l) symbols, all exported by $KERNEL"
fi

# Module package.
K=$WORK/kmod
install -Dm644 "$KO" "$K/lib/modules/$KERNEL/extra/$MODULE.ko"
install -Dm644 "$SRC/licenses/GPL-2.0.txt" "$K/usr/share/licenses/$PROJECT-kmod/GPL-2.0.txt"
mkdir -p "$K/install"
cat > "$K/install/slack-desc" <<EOF
$PROJECT-kmod: $PROJECT-kmod ($MODULE $VERSION for $KERNEL)
$PROJECT-kmod:
$PROJECT-kmod: $(modinfo -F description "$KO") kernel module.
$PROJECT-kmod: Upstream: $ORIGIN
$PROJECT-kmod: Commit: $COMMIT
$PROJECT-kmod: vermagic: $(modinfo -F vermagic "$KO")
$PROJECT-kmod:
$PROJECT-kmod:
$PROJECT-kmod:
$PROJECT-kmod:
$PROJECT-kmod:
EOF

# Firmware package, at the paths the module declares.
F=$WORK/firmware
for fw in $(modinfo -F firmware "$KO"); do
  case $fw in "$PROJECT/$NV"/*) ;; *) echo "unexpected firmware path $fw" >&2; exit 1 ;; esac
  install -Dm644 "$WORK/assets/$(basename "$fw")" "$F/lib/firmware/$fw"
done
for f in "$WORK/assets/NVIDIA-LICENSE" "$SRC/firmware/NOTICE.md" "$SRC"/licenses/*-MIT.txt; do
  install -Dm644 "$f" "$F/usr/share/licenses/$PROJECT-firmware/$(basename "$f")"
done
mkdir -p "$F/install"
cat > "$F/install/slack-desc" <<EOF
$PROJECT-firmware: $PROJECT-firmware (assets $NV for $MODULE $VERSION)
$PROJECT-firmware:
$PROJECT-firmware: Firmware generated by the $PROJECT build from pinned NVIDIA inputs.
$PROJECT-firmware: NVIDIA firmware remains under its own terms; see NOTICE.md.
$PROJECT-firmware: Commit: $COMMIT
$PROJECT-firmware:
$PROJECT-firmware:
$PROJECT-firmware:
$PROJECT-firmware:
$PROJECT-firmware:
$PROJECT-firmware:
EOF

KMOD_TXZ=$OUT/$PROJECT-kmod-$(echo "$VERSION" | tr - _)_$(echo "$KERNEL" | tr - _)-x86_64-$BUILD.txz
FW_TXZ=$OUT/$PROJECT-firmware-$(echo "$NV" | tr - _)-noarch-$BUILD.txz
python3 "$HERE/mktxz.py" "$K" "$KMOD_TXZ"
python3 "$HERE/mktxz.py" "$F" "$FW_TXZ"

for txz in "$KMOD_TXZ" "$FW_TXZ"; do
  echo "== $(basename "$txz")"
  tar -tvJf "$txz"
done
echo "vermagic: $(modinfo -F vermagic "$KO")"
echo "firmware: $(modinfo -F firmware "$KO" | tr '\n' ' ')"
echo "upstream: $PROJECT $VERSION $COMMIT"
